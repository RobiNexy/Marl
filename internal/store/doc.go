// Package store 定义持久化层的契约接口（阶段 0 只认证签名）。
//
// 设计原则 2（不可变的真相 + 可变的投影）：本层的实现是两个"真相之源"——
// Message Log（SQLite supervisor.db）与 Fossil（任务身份/代码/知识）——
// 之上的存取。所有"删除、摘要、重排、剪枝"只发生在投影（ContextView）层，
// Log 永远保留完整血缘。
//
// 具体存储后端（SQLite / Fossil CLI）在阶段 1 之后实现；这里只钉死接口。
//
// # 本包的三个源（不是四个）
//
//   - 真相之源：MessageLog、Ledger、Audit（审计是旁路证据，但一旦写下不可改）；
//   - 投影：ViewStore、SnapshotStore（丢了可重建/可再拍，失败不需要恢复流程）。
//
// 区分这两类的实际影响：只有真相之源的写入失败需要进入恢复流程；投影的
// 写入失败只需重试或放弃。把两者混为一谈会让"View 写不进去"这种小事
// 触发完整的崩溃恢复，或者反过来让"Log 写丢了"被当成可忽略。
//
// # 错误语义（全包统一）
//
//   - 哨兵见 errors.go，实现必须 %w 包装，调用方必须 errors.Is 匹配；
//   - ErrInvalid 表示**调用方 bug**（零值/参数写反），不重试、不降级；
//   - 查询类方法对"没有数据"用返回值表达（空切片 / LastSeq=0 / 空 View），
//     对"目标不存在"才用 ErrNotFound。这条区分很重要：把"没有"当错误会
//     让正常初始状态走进错误分支，把"目标不存在"当空值则会让引用失效
//     （如 ContextView 指向已消失的 Log）被静默吞掉。
//
// # 所有权契约（全包统一）
//
// 写接口把传入的结构体当作**输出参数**（就地回填 ID/Seq/Timestamp），
// 因此传入对象在写入后即冻结、不得并发复用；读接口返回的对象归调用方所有，
// 但不得修改其中集合的底层数据。所有接口都必须可并发调用。
